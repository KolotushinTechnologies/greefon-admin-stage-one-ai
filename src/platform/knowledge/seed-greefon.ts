export async function seedGreefonSite(docs: KnowledgeRepository, knowledge: KnowledgeService): Promise<void> {
  for (const item of DOCS) {
    const found = await docs.findByTitle(item.title);
    if (!found) {
      const payload: {
        title: string;
        body: string;
        fields?: KnowledgeField[];
        kind: KnowledgeKind;
        namespace: KnowledgeNamespace;
        actorTelegramId: string;
      } = {
        title: item.title,
        body: item.body,
        kind: item.kind,
        namespace: item.namespace,
        actorTelegramId: "system",
      };
      if (item.fields) {
        payload.fields = item.fields;
      }
      await knowledge.upsert(payload);
      continue;
    }
    if (docFields(found.fields).length === 0 && item.fields && item.fields.length > 0) {
      await knowledge.upsert({
        id: found._id,
        title: found.title,
        body: found.body,
        fields: item.fields,
        kind: found.kind,
        namespace: found.namespace,
        actorTelegramId: "system",
      });
    }
  }

  const pigulin = await docs.findByTitle("Пигулин Никита Александрович");
  if (pigulin) {
    await knowledge.setField({
      id: pigulin._id,
      key: "дан",
      value: "II дан",
      actorTelegramId: "system",
    });
    if (/I дан|1 дан|первый дан/i.test(pigulin.body) && !/II дан|2 дан/i.test(pigulin.body)) {
      await knowledge.upsert({
        id: pigulin._id,
        title: pigulin.title,
        body: pigulin.body.replace(/чёрный пояс I дан/gi, "чёрный пояс II дан").replace(/\bI дан\b/g, "II дан"),
        kind: pigulin.kind,
        namespace: pigulin.namespace,
        actorTelegramId: "system",
      });
    }
  }
}
